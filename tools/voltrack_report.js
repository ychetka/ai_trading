// voltrack_report.js - periodic aggregation of the voltrack forward log.
// Reads data/voltrack_state.jsonl (state rows from voltrack.js --watch)
// and data/voltrack_outcomes.jsonl (resolved signals from voltrack_join.js),
// produces VOLTRACK_REPORT.md: coverage, state/regime mix, signal-emission
// stats, per-setup/per-regime/per-state outcome breakdowns, and automatic
// flags per setup:
//   SIGNIFICANT   n >= --flag-n && meanR > 0 && winPct >= --flag-win
//   DEAD          n >= --flag-n && (meanR <= 0 || winPct < --dead-win)
//   INSUFFICIENT  otherwise (honest "not enough data")
//   SILENT        setup never emitted a signal in the whole log
//
//   node tools/voltrack_report.js              # print markdown
//   node tools/voltrack_report.js --write      # write VOLTRACK_REPORT.md
//   node tools/voltrack_report.js --json       # machine-readable

const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const { SETUP_LONG, SETUP_SHORT } = require('./voltrack.js');
const { summarize } = require('./voltrack_join.js');
const { arg, loadJsonlRotated } = require('./lib/store');
const STATE_FILE = arg('in', path.join(ROOT, 'data', 'voltrack_state.jsonl'));
const OUTCOME_FILE = arg('outcomes', path.join(ROOT, 'data', 'voltrack_outcomes.jsonl'));
const REPORT = arg('report', path.join(ROOT, 'VOLTRACK_REPORT.md'));
const FLAG_N = +arg('flag-n', 20), FLAG_WIN = +arg('flag-win', 35), DEAD_WIN = +arg('dead-win', 20);


function groupBy(rows, k) {
  const m = {};
  for (const r of rows) (m[r[k] ?? 'unknown'] = m[r[k] ?? 'unknown'] || []).push(r);
  return m;
}

function flagSetup(n, meanR, winPct, emitted) {
  if (emitted === 0) return 'SILENT';
  if (n < FLAG_N) return 'INSUFFICIENT';
  if (meanR > 0 && winPct >= FLAG_WIN) return 'SIGNIFICANT';
  if (meanR <= 0 || winPct < DEAD_WIN) return 'DEAD';
  return 'INSUFFICIENT';
}

function analyze(stateRows, outcomeRows) {
  const sigRows = stateRows.filter(r => (r.signals || []).length > 0);
  const emitted = {};
  for (const r of sigRows) {
    for (const s of r.signals) {
      const k = `${s.side}:${s.setup}`;
      emitted[k] = (emitted[k] || 0) + 1;
    }
  }
  const perSetup = {};
  for (const [k, list] of Object.entries(groupBy(outcomeRows, 'setup'))) {
    perSetup[k] = summarize(list);
  }
  const flags = {};
  // known classifier setups are seeded so a never-fired setup shows SILENT
  const setups = new Set([`long:${SETUP_LONG}`, `short:${SETUP_SHORT}`,
    ...Object.keys(emitted), ...Object.keys(perSetup),
    ...outcomeRows.map(o => `${o.side}:${o.setup}`)]);
  for (const k of setups) {
    const oc = outcomeRows.filter(o => `${o.side}:${o.setup}` === k);
    const s = oc.length ? summarize(oc) : { n: 0, meanR: null, winPct: null };
    // SILENT = never emitted AND never resolved; outcomes imply it did fire
    flags[k] = { flag: flagSetup(s.n, s.meanR, s.winPct, (emitted[k] || 0) + oc.length),
      n: s.n, meanR: s.meanR, winPct: s.winPct, emitted: emitted[k] || 0 };
  }
  return {
    coverage: {
      rows: stateRows.length,
      spanH: stateRows.length ? +((stateRows[stateRows.length - 1].ts - stateRows[0].ts) / 3600e3).toFixed(1) : 0,
      firstTs: stateRows[0] && stateRows[0].ts, lastTs: stateRows[stateRows.length - 1] && stateRows[stateRows.length - 1].ts,
    },
    states: Object.fromEntries(Object.entries(groupBy(stateRows, 'state')).map(([k, v]) => [k, v.length])),
    regimes: Object.fromEntries(Object.entries(groupBy(stateRows, 'regime')).map(([k, v]) => [k, v.length])),
    signals: { rowsWithSignals: sigRows.length, emitted },
    outcomes: {
      n: outcomeRows.length,
      overall: summarize(outcomeRows),
      perSetup, perRegime: Object.fromEntries(Object.entries(groupBy(outcomeRows, 'regime')).map(([k, v]) => [k, summarize(v)])),
      perState: Object.fromEntries(Object.entries(groupBy(outcomeRows, 'state')).map(([k, v]) => [k, summarize(v)])),
    },
    flags,
    thresholds: { flagN: FLAG_N, flagWin: FLAG_WIN, deadWin: DEAD_WIN },
  };
}

const tbl = (head, rows) => [head.join(' | '), head.map(() => '---').join(' | '), ...rows].join('\n');

function render(a) {
  const L = ['# Voltrack Forward-Log Report', ''];
  L.push('Generated by `tools/voltrack_report.js` - do not edit by hand.');
  L.push('');
  L.push('## Coverage');
  L.push('');
  L.push(`- Rows: **${a.coverage.rows}** over **${a.coverage.spanH}h**`);
  L.push(`- States: ${Object.entries(a.states).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'}`);
  const tr = a.coverage.rows || 1;
  L.push(`- Regimes: ${Object.entries(a.regimes).map(([k, v]) => `${k} ${(100 * v / tr).toFixed(1)}%`).join(', ') || 'none'}`);
  L.push('');
  L.push('## Signal emission');
  L.push('');
  if (Object.keys(a.signals.emitted).length) {
    L.push(tbl(['Setup', 'Emitted (rows)'], Object.entries(a.signals.emitted).map(([k, v]) => [k, v])));
  } else {
    L.push(`No signals emitted in ${a.coverage.rows} rows (${a.coverage.spanH}h). ` +
      'The classifier entry conditions have not fired yet - this is itself ' +
      'evidence: setups are rare, or thresholds need review at n>50 target.');
  }
  L.push('');
  L.push('## Outcomes');
  L.push('');
  const o = a.outcomes.overall;
  L.push(`Resolved: **${o.n}** (meanR ${o.meanR ?? '-'}, medianR ${o.medianR ?? '-'}, win ${o.winPct ?? '-'}%)`);
  L.push('');
  for (const [title, group] of [['Per setup', a.outcomes.perSetup],
    ['Per regime', a.outcomes.perRegime], ['Per state', a.outcomes.perState]]) {
    const entries = Object.entries(group);
    if (!entries.length) continue;
    L.push(`### ${title}`);
    L.push('');
    L.push(tbl(['Bucket', 'n', 'meanR', 'medianR', 'win%'],
      entries.map(([k, s]) => [k, s.n, s.meanR ?? '-', s.medianR ?? '-', s.winPct ?? '-'])));
    L.push('');
  }
  L.push('## Flags');
  L.push('');
  L.push(`Thresholds: SIGNIFICANT = n>=${a.thresholds.flagN} && meanR>0 && win>=${a.thresholds.flagWin}%; ` +
    `DEAD = n>=${a.thresholds.flagN} && (meanR<=0 || win<${a.thresholds.deadWin}%); else INSUFFICIENT.`);
  L.push('');
  if (Object.keys(a.flags).length) {
    L.push(tbl(['Setup', 'Flag', 'Emitted', 'n', 'meanR', 'win%'],
      Object.entries(a.flags).map(([k, f]) => [k, `**${f.flag}**`, f.emitted, f.n, f.meanR ?? '-', f.winPct ?? '-'])));
  } else {
    L.push('No setups have produced signals or outcomes yet.');
  }
  L.push('');
  return L.join('\n');
}

function main() {
  // state file rotated by voltrack.js --out -> merge the .1 tail;
  // outcomes .1 is forward-defense for when the joiner gains rotation
  const stateRows = loadJsonlRotated(STATE_FILE);
  const outcomeRows = loadJsonlRotated(OUTCOME_FILE);
  const a = analyze(stateRows, outcomeRows);
  if (process.argv.includes('--json')) { console.log(JSON.stringify(a, null, 1)); return; }
  const md = render(a);
  if (process.argv.includes('--write')) { fs.writeFileSync(REPORT, md); console.log(`wrote ${REPORT}`); }
  else process.stdout.write(md);
}
if (require.main === module) main();
module.exports = { analyze, render, flagSetup };
